const I18nContext = createContext<I18nContextType | undefined>(undefined);

function getNestedValue(obj: Translations, path: string): string | undefined {
  const keys = path.split('.');
  let result: TranslationValue = obj;

  for (const key of keys) {
    if (typeof result === 'object' && result !== null && key in result) {
      result = result[key];
    } else {
      return undefined;
    }
  }

  return typeof result === 'string' ? result : undefined;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== 'undefined') {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored && (stored === 'en' || stored === 'fr' || stored === 'ar')) {
        return stored as Language;
      }
    }
    return 'en';
  });

  // Persist language changes
  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, language);
    // Update document direction for RTL support
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = useCallback((lang: Language) => {
    setLanguageState(lang);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>): string => {
      let text = getNestedValue(translations[language], key);

      if (!text) {
        // Fallback to English
        text = getNestedValue(translations.en, key);
      }

      if (!text) {
        // Return key if no translation found
        return key;
      }

      // Replace parameters like {{param}}
      if (params) {
        Object.entries(params).forEach(([paramKey, value]) => {
          text = text!.replace(new RegExp(`\\{\\{${paramKey}\\}\\}`, 'g'), String(value));
        });
      }

      return text;
    },
    [language]
  );

  const dir: 'ltr' | 'rtl' = language === 'ar' ? 'rtl' : 'ltr';

  const contextValue = useMemo(
    () => ({
      language,
      setLanguage,
      t,
      dir,
    }),
    [language, setLanguage, t, dir]
  );

  return <I18nContext.Provider value={contextValue}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }
  return context;
}

// Shorthand hook for just the translation function
export function useTranslation() {
  const { t, language, dir } = useI18n();
  return { t, language, dir };
}
